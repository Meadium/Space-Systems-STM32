/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */
  ws2812b_init(&htim1);
  /* USER CODE END 2 */

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

  uint32_t elapsed = 0U; // Czas od początku okresu zmiany koloru
  uint32_t phase = 0U; // Faza jednego okresu diody


  while (1)
  {
	  uint32_t now = HAL_GetTick();



	  if (button_event != 0U) // Jeżeli przycisk był naciśnięty odpala się niebieska dioda
	  {
		  __disable_irq();
		  button_event = 0U;
		  __enable_irq();

		  if (state != STATE_BLUE)
		  {
			  state = STATE_BLUE;
			  state_start = now;
		  }
	  }



	  switch(state){ // Wybór diody

	  	  case STATE_RED:
	  	  {
	  		 elapsed = now - state_start;
	  		 phase = elapsed % BLINK_MS;


	  		  r = (phase < BLINK_MS / 2U) ? 255 : 0; // Czerwony led jest włączony przez połowę okresu diody
	  		  g = 0U;
	  		  b = 0U;

	  		  if (elapsed >= PERIOD_MS){ // Po 3s zmienia się na zielony
	  			  state = STATE_GREEN;
	  			  state_start = now;
	  		  }

	  		  break;
	  	  }

	  	  case STATE_GREEN:
	  	  {
	  		  elapsed = now - state_start;
			  phase = elapsed % BLINK_MS;

	  		  r = 0;
	  		  g = (uint8_t)((phase * 255U)/BLINK_MS); // Zmienia się w kształt sygnału piłokształtnego
	  		  b = 0;

	  		if (elapsed >= PERIOD_MS) // Po 3s zmienia się z powrotem na czerwony
	  		{
				  state = STATE_RED;
				  state_start = now;
		    }

	  		break;
	  	  }

	  	  case STATE_BLUE:
	  	  {
	  		elapsed = now - state_start;


			if (elapsed < 3000U)
			{
				r = 0U;
				b = ((elapsed / BLINK_MS) % 2U == 0U) ? 255U : 0U; // mignięcie 3 razy
				g = 0U;
			}
			else
			{						// Po mignięciu 3 razy zmienia się na czerwoną diodę
				state = STATE_RED;
				state_start = now;

				r = 255U;
				g = 0U;
				b = 0U;
			}

			break;
	  	  }

	  	  default:
			{
				state = STATE_RED;
				state_start = now;
				break;
			}
	  }


	  if ((uint32_t)(now - last_frame) >= FRAME_MS)  // Jeżeli od ostatniego update'u upłynęło wystarczająco czasu to następuje następny
	      {
	          last_frame = now;

	          ws2812b_wait(&htim1);

	          for (uint32_t i = 0; i < LED_COUNT; i++)
	          {
	              ws2812b_set_color(i,r,g,b);
	          }

	          ws2812b_update(&htim1);
	      }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

  }
  /* USER CODE END 3 */
}

